/* ==========================================================================
   alerts.js — Early Warning page: summary, thresholds, alert log
   ========================================================================== */

'use strict';

let thresholds = { Advisory: 45, Warning: 60, Severe: 75 };
let actions = {};

function renderSummary(counts, total) {
  document.getElementById('sumAdvisory').textContent = counts.Advisory || 0;
  document.getElementById('sumWarning').textContent = counts.Warning || 0;
  document.getElementById('sumSevere').textContent = counts.Severe || 0;
  document.getElementById('alertNotice').textContent =
    `${total} unacknowledged alert(s). Generated by a configurable rule on a demonstration risk index — ` +
    `not a scientific forecast and not an official emergency service.`;
}

function renderThresholds() {
  const tbody = document.getElementById('thresholdRows');
  tbody.innerHTML = ALERT_ORDER.map(level => `
    <tr data-level="${level}">
      <td><span class="badge-level" data-level="${level}">${level}</span></td>
      <td>Risk index ≥ ${thresholds[level]}</td>
      <td class="small">${esc((actions[level] || '').slice(0, 90))}…</td>
    </tr>`).join('');
}

async function loadAlerts() {
  const box = document.getElementById('alertLog');
  const showAck = document.getElementById('showAck').checked;
  box.innerHTML = '<p class="muted small">Loading alerts…</p>';
  try {
    const data = await api('/api/alerts?limit=100&include_ack=' + (showAck ? '1' : '0'));
    thresholds = data.thresholds || thresholds;
    actions = data.actions || actions;
    renderThresholds();
    renderSummary(data.unacknowledged_by_level || {}, data.total_unacknowledged || 0);

    if (!data.alerts.length) {
      box.innerHTML = '<p class="muted small">No alerts to show. All monitored risk scores are below the configured thresholds.</p>';
      return;
    }
    box.innerHTML = data.alerts.map(a => alertItemHtml(a, { showAck: true })).join('');
    bindAckButtons(box, loadAlerts);
  } catch (err) {
    box.innerHTML = '<p class="muted small">Could not load alerts: ' + esc(err.message) + '</p>';
  }
}

document.addEventListener('DOMContentLoaded', () => {
  const refresh = document.getElementById('alertsRefreshBtn');
  if (refresh) refresh.addEventListener('click', () => { loadAlerts(); toast('Alert log refreshed.', 'ok'); });
  const showAck = document.getElementById('showAck');
  if (showAck) showAck.addEventListener('change', loadAlerts);
  const ackAll = document.getElementById('ackAllPageBtn');
  if (ackAll) ackAll.addEventListener('click', async () => {
    try {
      const res = await api('/api/alerts/ack-all', { method: 'POST' });
      toast(res.acknowledged_count + ' alert(s) marked as read.', 'ok');
      loadAlerts();
      refreshNotificationPanel();
    } catch (err) {
      toast('Could not update alerts: ' + err.message, 'error');
    }
  });
  window.onAlertsChanged = loadAlerts;
  loadAlerts();
  setInterval(loadAlerts, 60000);
});
